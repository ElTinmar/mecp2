function F2(datadir)
    rng('default')
    table_log = start_table('table_F2.txt'); %#ok<NASGU>

    % load the file names
    datafiles = get_datafiles_F2(fullfile(datadir,'Stimulation_Contrast'));

    %% extract fluorescence data around the onset of each stimuli -------------
    fps = 1000/256;
    time_window = [-3.5 7]; 
    neuralActivityAroundStim = extract_stim_contrast_F2(...
        datafiles,...
        time_window,...
        fps);
    %neuralActivityAroundStim = extract_stim_retino(datafiles,time_window,fps);

    %% bootstrap the difference of activity before vs after stim -------------- 
    % bootstrap the difference of activity between time_span seconds before the 
    % onset and time_span seconds after the onset of stimulation
    time_span = 3;
    thresh = 5;
    boot = bootstrap_diffBeforeAfterStim(...
        neuralActivityAroundStim,...
        time_span,...
        'binary',...
        thresh);

    %% get responsive cells ---------------------------------------------------
    thresh_num_trial = get_num_trials(boot,0.05,15);
    [resp_allStim, resp_perStim] = get_resp_cells(...
        boot,...
        thresh_num_trial);

    %% compute peak / integral / FWHM -----------------------------------------
    [DFF_properties, Binary_properties] = response_properties(...
        neuralActivityAroundStim,...
        resp_perStim,...
        resp_allStim,...
        6); 
    
    %% maximum likelihood decoder ---------------------------------------------
    time_span = 3;
    nrep = 10;
    N_samp = [5 25 100 300 500];
    stim_subset = 2:9;
    [decoding,confusion,accuracy] = decoder(...
        neuralActivityAroundStim,...
        time_span,...
        stim_subset,...
        nrep,...
        N_samp);

    %% choose example larva ---------------------------------------------------
    example.wt = 6;
    example.mecp2 = 1;

    %% save results -----------------------------------------------------------
    save('fig2.mat',...
        'neuralActivityAroundStim',...
        'resp_allStim',...
        'resp_perStim',...
        'DFF_properties',...
        'Binary_properties',...
        'decoding',...
        'confusion',...
        'accuracy',...
        'stim_subset',...
        'N_samp',...
        'example',...
        'time_span',...
        '-v7.3');

    %% plot results -----------------------------------------------------------
    f = plot_F2(...
        neuralActivityAroundStim,...
        resp_allStim,...
        DFF_properties,...
        Binary_properties,...
        decoding,...
        confusion,...
        accuracy,...
        N_samp,...
        example,...
        stim_subset);

    %% save figures -----------------------------------------------------------
    save_figure(f,'fig2');


    %% supplementary movie ----------------------------------------------------
    ex_sup.wt = 6;
    ex_sup.mecp2 = 1;
    thicken_ROI = [true,true];
    stim_duration = 1;
    speedup = 1; % how many times real time speed
    plot_isocurve = false;
    SupMovie_neuralActivity(...
        neuralActivityAroundStim,...
        resp_perStim,...
        ex_sup,...
        stim_subset,...
        stim_duration,...
        thicken_ROI,...
        speedup,...
        plot_isocurve,...
        'SupMovie_F2.avi')
end

