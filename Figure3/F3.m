function F3(datadir)
    rng('default')
    table_log = start_table('table_F3.txt'); %#ok<NASGU>

    % load the file names
    datafiles = get_datafiles_F3(fullfile(datadir,'Stimulation_Azimuth'));

    %% extract fluorescence data around the onset of each stimuli -------------
    fps = 500/256;
    time_window = [-3.5 7]; % 3.5 second before and 7 second after stim onset
    neuralActivityAroundStim = extract_stim_F3(...
        datafiles,...
        time_window,...
        fps);


    %% bootstrap the difference of activity before vs after stim -------------- 
    % bootstrap the difference of activity between time_span seconds before the 
    % onset and time_span seconds after the onset of stimulation
    time_span = 3;
    thresh = 5;
    boot = bootstrap_diffBeforeAfterStim(...
        neuralActivityAroundStim,...
        time_span,...
        'binary',...
        thresh);

    %% get responsive cells ---------------------------------------------------
    thresh_num_trial = get_num_trials(boot,0.05,20);
    [resp_allStim, resp_perStim] = get_resp_cells(...
        boot,...
        thresh_num_trial);

    %% compute peak / integral / FWHM -----------------------------------------
    [DFF_properties, Binary_properties] = response_properties(...
        neuralActivityAroundStim,...
        resp_perStim,...
        resp_allStim,...
        6);   

    %% maximum likelihood decoder ---------------------------------------------
    time_span = 3;
    nrep = 10;
    N_samp = [5 25 100 250 400];

    degree_char = char(176);
    stim_label = {'\0'};
    azimuth = [15, 35, 40, 50];
    for i = 1:length(azimuth)
        stim_label{i+1} = [num2str(azimuth(i)) degree_char];
    end

    stim_subset = 2:length(azimuth)+1;

    [decoding,confusion,accuracy] = decoder(...
        neuralActivityAroundStim,...
        time_span,...
        stim_subset,...
        nrep,...
        N_samp);

    %% choose example larva ---------------------------------------------------
    example.wt = 1;
    example.mecp2 = 1;

    %% save results -----------------------------------------------------------
    save('fig3.mat',...
        'neuralActivityAroundStim',...
        'nrep',...
        'resp_allStim',...
        'resp_perStim',...
        'DFF_properties',...
        'Binary_properties',...
        'decoding',...
        'confusion',...
        'accuracy',...
        'stim_label',...
        'stim_subset',...
        'N_samp',...
        'example',...
        '-v7.3');

    %% plot results -----------------------------------------------------------
    f = plot_F3(...
        neuralActivityAroundStim,...
        resp_allStim,...
        DFF_properties,...
        Binary_properties,...
        decoding,...
        confusion,...
        accuracy,...
        N_samp,...
        example,...
        stim_label,...
        stim_subset);

    save_figure(f,'fig3');


    %% supplementary figure ---------------------------------------------------
    example.wt = 1;
    example.mecp2 = 1;
    Sf = plot_SupF3(...
        neuralActivityAroundStim,...
        resp_allStim,...
        stim_label,...
        stim_subset,...
        azimuth,...
        example,...
        confusion,...
        decoding,...
        N_samp);

    save_figure(Sf,'figS2');

    %% supplementary movie ----------------------------------------------------
    ex_sup.wt = 1;
    ex_sup.mecp2 = 6; % 6 is ok, 9 too
    thicken_ROI = [false,true];
    stim_subset = 2:5;
    speedup = 1.75; % how many times real time speed
    stim_duration = 1;
    time_span = 3;
    plot_isocurve = true;

    % be less restrictive on resp cells for center of mass estimation using KDE
    thresh = 15;
    boot = bootstrap_diffBeforeAfterStim(...
        neuralActivityAroundStim,...
        time_span,...
        'binary',...
        thresh);

    % get responsive cells ---------------------------------------------------
    thresh_num_trial = get_num_trials(boot,0.1,20);
    [resp_allStim, resp_perStim] = get_resp_cells(...
        boot,...
        thresh_num_trial);

    % check responsive cells -------------------------------------------------
    ind_wt = find(~neuralActivityAroundStim.ismecp2);
    ind_mecp2 = find(neuralActivityAroundStim.ismecp2);
    %topography(datafiles,ind_wt(ex_sup.wt),resp_perStim);
    %topography(datafiles,ind_mecp2(ex_sup.mecp2),resp_perStim);
    
    SupMovie_neuralActivity(...
        neuralActivityAroundStim,...
        resp_perStim,...
        ex_sup,...
        stim_subset,...
        stim_duration,...
        thicken_ROI,...
        speedup,...
        plot_isocurve,...
        'SupMovie_F3.avi')
end